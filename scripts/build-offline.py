"""Run after changing the guide, photos, icons, or offline.js."""
from pathlib import Path
import hashlib, json
root = Path(__file__).resolve().parent.parent
files = ['index.html', 'offline.js', 'manifest.webmanifest'] + sorted(str(p.relative_to(root)) for folder in ['images', 'icons'] for p in (root / folder).rglob('*') if p.is_file() and not p.name.startswith('.'))
version = hashlib.sha256(b''.join(p.encode() + (root / p).read_bytes() for p in files)).hexdigest()[:16]
worker = '''// Generated by scripts/build-offline.py; caching behavior lives in this template.
const CACHE = 'china-trip-VERSION';
const ASSETS = FILES;
const base = self.registration.scope;
self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // Small batches avoid flooding a phone connection with photo requests.
    for (let i = 0; i < ASSETS.length; i += 6) {
      await cache.addAll(ASSETS.slice(i, i + 6).map(path => new Request(new URL(path, base), {cache: 'reload'})));
    }
    await self.skipWaiting();
  })());
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) {
      if (key.startsWith('china-trip-') && key !== CACHE) await caches.delete(key);
    }
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', event => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || !url.href.startsWith(base)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    // Serve a complete version together; checking sw.js online installs updates.
    const path = url.href.slice(base.length).split('?')[0];
    const key = event.request.mode === 'navigate' ? 'index.html' : path;
    const saved = await cache.match(new URL(key, base));
    return saved || fetch(event.request);
  })());
});
'''
(root / 'sw.js').write_text(worker.replace('VERSION', version).replace('FILES', json.dumps(files, indent=2)))
print(f'Offline bundle: {len(files)} files, {sum((root / p).stat().st_size for p in files)/1024/1024:.1f} MiB')
